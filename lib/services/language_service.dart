  Future<void> init() async {
    try {
      final sp = await SharedPreferences.getInstance();
      final savedCode = sp.getString('app_lang_code') ?? 'id';
      currentLangNotifier.value = savedCode;
    } catch (_) {}
  }

  Future<void> changeLanguage(String langCode) async {
    if (!_translations.containsKey(langCode)) return;
    currentLangNotifier.value = langCode;

    try {
      final sp = await SharedPreferences.getInstance();
      await sp.setString('app_lang_code', langCode);
    } catch (_) {}
  }

  String getText(String key) {
    final langCode = currentLangNotifier.value;
    final dict = _translations[langCode] ?? _translations['id']!;
    return dict[key] ?? _translations['id']![key] ?? key;
  }

  String get currentLanguageName {
    final code = currentLangNotifier.value;
    return languageNames[code] ?? 'Bahasa Indonesia';
  }
